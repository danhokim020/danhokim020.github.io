#!/usr/bin/env python3
"""
Master Data Synchronizer for Danho Kim's Homepage
Synchronizes CSV files from `_csv/` to Jekyll's native formats:
  1. _csv/about.csv        -> _data/about.yml
  2. _csv/publications.csv -> _bibliography/papers.bib (omits bibtex_show to remove Bib button)
  3. _csv/cv.csv          -> _data/cv.yml (RenderCV schema)
  4. _csv/ego_network.csv  -> _data/ego_network.yml

Ensures no .csv files reside in _data/ to prevent Jekyll site.data collisions!
"""

import csv
import os
import shutil
import sys
from pathlib import Path

# Force UTF-8 encoding for stdout on Windows
if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

ROOT_DIR = Path(__file__).resolve().parent.parent
CSV_DIR = ROOT_DIR / "_csv"
DATA_DIR = ROOT_DIR / "_data"
BIB_DIR = ROOT_DIR / "_bibliography"

def ensure_csv_dir():
    CSV_DIR.mkdir(parents=True, exist_ok=True)
    # Check if user placed CSV files in _data/ and migrate them to _csv/
    for name in ["about.csv", "cv.csv", "ego_network.csv", "publications.csv"]:
        data_csv = DATA_DIR / name
        target_csv = CSV_DIR / name
        if data_csv.exists():
            print(f"[Migrate] Found {data_csv.name} in _data/, migrating to _csv/...")
            shutil.copy2(data_csv, target_csv)
            try:
                data_csv.unlink()
            except Exception as e:
                print(f"[Warning] Could not remove {data_csv}: {e}")

def get_val(row, key, default=""):
    val = row.get(key)
    if val is None:
        return default
    return str(val).strip()

def format_yaml_str(val):
    if not val:
        return '""'
    s = str(val).strip().replace('\\', '\\\\').replace('"', '\\"')
    return f'"{s}"'

def sync_about():
    csv_path = CSV_DIR / "about.csv"
    yml_path = DATA_DIR / "about.yml"
    
    if not csv_path.exists():
        print(f"[Sync About] {csv_path} not found, skipping.")
        return
        
    data = {
        "subtitle": "",
        "greeting": "",
        "intro_lead": "",
        "focus_points": [],
        "methods_summary": "",
        "footer_note": ""
    }
    
    with open(csv_path, mode='r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        for row in reader:
            sec = get_val(row, 'section').lower()
            title = get_val(row, 'title')
            content = get_val(row, 'content')
            
            if sec == 'subtitle':
                data['subtitle'] = content
            elif sec == 'greeting':
                data['greeting'] = content
            elif sec == 'intro_lead':
                data['intro_lead'] = content
            elif sec == 'focus_point':
                if title or content:
                    data['focus_points'].append({'title': title, 'content': content})
            elif sec == 'methods_summary':
                data['methods_summary'] = content
            elif sec == 'footer_note':
                data['footer_note'] = content

    lines = [
        "# AUTO-GENERATED from _csv/about.csv by bin/sync_site_data.py",
        "# DO NOT EDIT THIS FILE DIRECTLY - Edit _csv/about.csv instead!",
        f"subtitle: {format_yaml_str(data['subtitle'])}",
        f"greeting: {format_yaml_str(data['greeting'])}",
        f"intro_lead: {format_yaml_str(data['intro_lead'])}",
        f"methods_summary: {format_yaml_str(data['methods_summary'])}",
        f"footer_note: {format_yaml_str(data['footer_note'])}",
        "focus_points:"
    ]
    for fp in data['focus_points']:
        lines.append(f"  - title: {format_yaml_str(fp['title'])}")
        lines.append(f"    content: {format_yaml_str(fp['content'])}")
        
    with open(yml_path, mode='w', encoding='utf-8') as f:
        f.write("\n".join(lines) + "\n")
    print(f"[Sync About] Generated {yml_path}")

def sync_publications():
    csv_path = CSV_DIR / "publications.csv"
    bib_path = BIB_DIR / "papers.bib"
    
    if not csv_path.exists():
        print(f"[Sync Publications] {csv_path} not found, skipping.")
        return
        
    entries = []
    with open(csv_path, mode='r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        for row in reader:
            p_id = get_val(row, 'id')
            if not p_id:
                continue
            
            fields = []
            abbr = get_val(row, 'abbr')
            if abbr:
                fields.append(f"  abbr        = {{{abbr}}},")
                
            # Intentionally omit bibtex_show to completely remove the Bib button per user request!
            
            title = get_val(row, 'title')
            if title:
                fields.append(f"  title       = {{{title}}},")
                
            author = get_val(row, 'author')
            if author:
                fields.append(f"  author      = {{{author}}},")
                
            journal = get_val(row, 'journal')
            if journal:
                fields.append(f"  journal     = {{{journal}}},")
                
            volume = get_val(row, 'volume')
            if volume:
                fields.append(f"  volume      = {{{volume}}},")
                
            number = get_val(row, 'number')
            if number:
                fields.append(f"  number      = {{{number}}},")
                
            pages = get_val(row, 'pages')
            if pages:
                if '-' in pages and not '--' in pages:
                    pages = pages.replace('-', '--')
                fields.append(f"  pages       = {{{pages}}},")
                
            year = get_val(row, 'year')
            if year:
                fields.append(f"  year        = {{{year}}},")
                
            abstract = get_val(row, 'abstract')
            if abstract:
                fields.append(f"  abstract    = {{{abstract}}},")
                
            selected = get_val(row, 'selected', 'false').lower()
            if selected in ('true', 'yes', '1'):
                fields.append(f"  selected    = {{true}}")
            else:
                fields.append(f"  selected    = {{false}}")
                
            entry_str = f"@article{{{p_id},\n" + "\n".join(fields) + "\n}"
            entries.append(entry_str)
            
    header = [
        "---",
        "---",
        "",
        "% -----------------------------------------------------------------------------",
        "% AUTO-GENERATED from _csv/publications.csv by bin/sync_site_data.py",
        "% DO NOT EDIT THIS FILE DIRECTLY - Edit _csv/publications.csv instead!",
        "% -----------------------------------------------------------------------------",
        ""
    ]
    bib_content = "\n".join(header) + "\n\n".join(entries) + "\n"
    with open(bib_path, mode='w', encoding='utf-8') as f:
        f.write(bib_content)
    print(f"[Sync Publications] Generated {bib_path} with {len(entries)} papers.")

def sync_cv():
    csv_path = CSV_DIR / "cv.csv"
    yml_path = DATA_DIR / "cv.yml"
    
    if not csv_path.exists():
        print(f"[Sync CV] {csv_path} not found, skipping.")
        return
        
    profile = {
        "name": "Danho Kim",
        "label": "",
        "email": "danhokim@yonsei.ac.kr",
        "location": "",
        "image": "",
        "summary": ""
    }
    social_networks = []
    education = []
    skills = []
    experience = []
    awards = []
    
    with open(csv_path, mode='r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        for row in reader:
            sec = get_val(row, 'section').lower()
            title = get_val(row, 'title')
            subtitle = get_val(row, 'subtitle')
            institution = get_val(row, 'institution')
            start_date = get_val(row, 'start_date')
            end_date = get_val(row, 'end_date')
            loc = get_val(row, 'location')
            details = get_val(row, 'details')
            
            if sec == 'profile':
                if title: profile['name'] = title
                if subtitle: profile['label'] = subtitle
                if institution and '@' in institution: profile['email'] = institution
                if loc: profile['location'] = loc
                if details: profile['summary'] = details
            elif sec == 'email':
                profile['email'] = title or subtitle or institution
            elif sec == 'social':
                if title and institution:
                    social_networks.append({'network': title, 'username': institution})
                elif title and subtitle:
                    social_networks.append({'network': title, 'username': subtitle})
            elif sec == 'education':
                highlights = [h.strip() for h in details.split(';') if h.strip()] if details else []
                education.append({
                    'institution': institution or title,
                    'location': loc,
                    'area': subtitle,
                    'studyType': title,
                    'start_date': start_date,
                    'end_date': end_date,
                    'highlights': highlights
                })
            elif sec == 'skills':
                keywords = [k.strip() for k in details.split(';') if k.strip()] if details else []
                skills.append({
                    'name': title,
                    'level': subtitle,
                    'keywords': keywords
                })
            elif sec in ('experience', 'work'):
                highlights = [h.strip() for h in details.split(';') if h.strip()] if details else []
                experience.append({
                    'company': institution or title,
                    'position': subtitle,
                    'location': loc,
                    'start_date': start_date,
                    'end_date': end_date,
                    'highlights': highlights
                })
            elif sec in ('awards', 'honors'):
                awards.append({
                    'title': title,
                    'awarder': institution,
                    'date': start_date,
                    'summary': details
                })

    lines = [
        "# AUTO-GENERATED from _csv/cv.csv by bin/sync_site_data.py",
        "# DO NOT EDIT THIS FILE DIRECTLY - Edit _csv/cv.csv instead!",
        "cv:",
        f"  name: {format_yaml_str(profile['name'])}",
        f"  label: {format_yaml_str(profile['label'])}",
        f"  email: {format_yaml_str(profile['email'])}",
        f"  location: {format_yaml_str(profile['location'])}",
        '  image: ""',
        f"  summary: {format_yaml_str(profile['summary'])}",
        "",
        "  social_networks:"
    ]
    for sn in social_networks:
        lines.append(f"    - network: {sn['network']}")
        lines.append(f"      username: {sn['username']}")
        
    lines.append("")
    lines.append("  sections:")
    if education:
        lines.append("    Education:")
        for edu in education:
            lines.append(f"      - institution: {format_yaml_str(edu['institution'])}")
            if edu['location']: lines.append(f"        location: {format_yaml_str(edu['location'])}")
            if edu['area']: lines.append(f"        area: {format_yaml_str(edu['area'])}")
            if edu['studyType']: lines.append(f"        studyType: {format_yaml_str(edu['studyType'])}")
            if edu['start_date']: lines.append(f"        start_date: {edu['start_date']}")
            if edu['end_date']: lines.append(f"        end_date: {edu['end_date']}")
            if edu['highlights']:
                lines.append("        highlights:")
                for h in edu['highlights']:
                    lines.append(f"          - {format_yaml_str(h)}")
        lines.append("")

    if experience:
        lines.append("    Experience:")
        for exp in experience:
            lines.append(f"      - company: {format_yaml_str(exp['company'])}")
            if exp['position']: lines.append(f"        position: {format_yaml_str(exp['position'])}")
            if exp['location']: lines.append(f"        location: {format_yaml_str(exp['location'])}")
            if exp['start_date']: lines.append(f"        start_date: {exp['start_date']}")
            if exp['end_date']: lines.append(f"        end_date: {exp['end_date']}")
            if exp['highlights']:
                lines.append("        highlights:")
                for h in exp['highlights']:
                    lines.append(f"          - {format_yaml_str(h)}")
        lines.append("")

    if awards:
        lines.append("    Honors and Awards:")
        for aw in awards:
            lines.append(f"      - title: {format_yaml_str(aw['title'])}")
            if aw['date']: lines.append(f"        date: {aw['date']}")
            if aw['awarder']: lines.append(f"        awarder: {format_yaml_str(aw['awarder'])}")
            if aw['summary']: lines.append(f"        summary: {format_yaml_str(aw['summary'])}")
        lines.append("")

    if skills:
        lines.append("    Skills:")
        for sk in skills:
            lines.append(f"      - name: {format_yaml_str(sk['name'])}")
            if sk['level']: lines.append(f"        level: {format_yaml_str(sk['level'])}")
            if sk['keywords']:
                lines.append("        keywords:")
                for kw in sk['keywords']:
                    lines.append(f"          - {format_yaml_str(kw)}")
        lines.append("")

    with open(yml_path, mode='w', encoding='utf-8') as f:
        f.write("\n".join(lines) + "\n")
    print(f"[Sync CV] Generated {yml_path}")

def sync_network():
    ego_script = ROOT_DIR / "bin" / "sync_ego_network.py"
    if ego_script.exists():
        import subprocess
        subprocess.run([sys.executable, str(ego_script)], check=True)

def sync_all():
    print("=== Master Data Synchronization Started ===")
    ensure_csv_dir()
    sync_about()
    sync_publications()
    sync_cv()
    sync_network()
    print("=== Master Data Synchronization Finished Successfully! ===")

if __name__ == "__main__":
    sync_all()
